create table if not exists public.courts (
    id bigint generated by default as identity primary key,
    name text not null unique,
    max_players integer not null default 12 check (max_players > 0),
    status text not null default 'available',
    is_active boolean not null default true,
    created_at timestamptz not null default now()
);

create table if not exists public.bookings (
    id bigint generated by default as identity primary key,
    booking_reference text not null unique,
    booking_type text not null check (booking_type in ('open_play', 'court_rental')),
    booking_date date not null,
    start_time time not null,
    end_time time not null,
    court_id bigint not null references public.courts(id),
    host_name text not null,
    contact_number text not null,
    email text not null default '',
    player_names text not null default '',
    players_count integer not null default 1 check (players_count > 0),
    status text not null default 'confirmed' check (status in ('confirmed', 'cancelled')),
    payment_amount numeric(10, 2) not null default 0 check (payment_amount >= 0),
    payment_status text not null default 'pending' check (payment_status in ('pending', 'paid')),
    payment_reference text,
    notes text not null default '',
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

alter table public.bookings
    add column if not exists payment_amount numeric(10, 2) not null default 0 check (payment_amount >= 0),
    add column if not exists payment_status text not null default 'pending' check (payment_status in ('pending', 'paid')),
    add column if not exists payment_reference text;

create index if not exists idx_bookings_court_schedule
    on public.bookings (court_id, booking_date, status, start_time, end_time);
create index if not exists idx_bookings_date_type
    on public.bookings (booking_date desc, booking_type);
create unique index if not exists idx_bookings_payment_reference_unique
    on public.bookings (payment_reference)
    where payment_reference is not null;

create table if not exists public.booking_players (
    id bigint generated by default as identity primary key,
    booking_id bigint not null references public.bookings(id) on delete cascade,
    player_name text not null
);

create index if not exists idx_booking_players_booking_id
    on public.booking_players (booking_id, id);

create table if not exists public.admins (
    id bigint generated by default as identity primary key,
    username text not null unique,
    password_hash text not null,
    full_name text not null,
    is_active boolean not null default true,
    created_at timestamptz not null default now()
);

