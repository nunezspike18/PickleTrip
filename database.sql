create or replace function public.create_booking(p_booking jsonb, p_players jsonb)
returns jsonb
language plpgsql
set search_path = public, pg_temp
as $$
declare
    v_court_id bigint := (p_booking ->> 'court_id')::bigint;
    v_booking_date date := (p_booking ->> 'booking_date')::date;
    v_start_time time := (p_booking ->> 'start_time')::time;
    v_end_time time := (p_booking ->> 'end_time')::time;
    v_booking_type text := p_booking ->> 'booking_type';
    v_players_count integer := (p_booking ->> 'players_count')::integer;
    v_payment_reference text := nullif(p_booking ->> 'payment_reference', '');
    v_max_players integer;
    v_open_play_players integer;
    v_conflict boolean;
    v_booking public.bookings;
begin
    if v_booking_type not in ('open_play', 'court_rental')
       or v_booking_date < current_date
       or v_players_count < 1 then
        raise exception 'Please choose valid booking details.' using errcode = 'P0001';
    end if;

    if v_booking_type = 'open_play'
       and (v_payment_reference is null or v_payment_reference !~ '^[A-Za-z0-9-]{5,40}$') then
        raise exception 'Open-play bookings require a valid GCash transaction number.' using errcode = 'P0001';
    end if;

    perform pg_advisory_xact_lock(hashtext(v_booking_date::text), v_court_id::integer);

    select max_players into v_max_players
    from public.courts
    where id = v_court_id and is_active = true;

    if not found then
        raise exception 'This court is no longer available.' using errcode = 'P0001';
    end if;

    if v_players_count > v_max_players then
        raise exception 'This booking exceeds the court player limit.' using errcode = 'P0001';
    end if;

    select coalesce(sum(players_count), 0)::integer into v_open_play_players
    from public.bookings
    where court_id = v_court_id
      and booking_date = v_booking_date
      and status = 'confirmed'
      and booking_type = 'open_play'
      and start_time = v_start_time
      and end_time = v_end_time;

    select exists (
        select 1
        from public.bookings b
        where b.court_id = v_court_id
          and b.booking_date = v_booking_date
          and b.status = 'confirmed'
          and not (
              v_booking_type = 'open_play'
              and b.booking_type = 'open_play'
              and b.start_time = v_start_time
              and b.end_time = v_end_time
          )
          and (v_booking_date + v_start_time)
              < (b.booking_date + b.end_time + case when b.end_time <= b.start_time then interval '1 day' else interval '0' end)
          and (b.booking_date + b.start_time)
              < (v_booking_date + v_end_time + case when v_end_time <= v_start_time then interval '1 day' else interval '0' end)
    ) into v_conflict;

    if v_conflict then
        raise exception 'This court is already booked for the selected date and time.' using errcode = 'P0001';
    end if;

    if v_booking_type = 'open_play' and v_open_play_players + v_players_count > v_max_players then
        raise exception 'There are not enough open-play spots left in this session.' using errcode = 'P0001';
    end if;

    insert into public.bookings (
        booking_reference, booking_type, booking_date, start_time, end_time, court_id,
        host_name, contact_number, email, player_names, players_count, status,
        payment_amount, payment_status, payment_reference, notes, updated_at
    ) values (
        p_booking ->> 'booking_reference',
        v_booking_type,
        v_booking_date,
        v_start_time,
        v_end_time,
        v_court_id,
        p_booking ->> 'host_name',
        p_booking ->> 'contact_number',
        coalesce(p_booking ->> 'email', ''),
        coalesce(p_booking ->> 'player_names', ''),
        v_players_count,
        'confirmed',
        (p_booking ->> 'payment_amount')::numeric,
        'pending',
        v_payment_reference,
        'Booking created from public website.',
        now()
    )
    returning * into v_booking;

    insert into public.booking_players (booking_id, player_name)
    select v_booking.id, names.player_name
    from jsonb_array_elements_text(coalesce(p_players, '[]'::jsonb)) as names(player_name);

    return jsonb_build_object('id', v_booking.id, 'booking_reference', v_booking.booking_reference);
end;
$$;

revoke all on function public.create_booking(jsonb, jsonb) from public, anon, authenticated;
grant execute on function public.create_booking(jsonb, jsonb) to service_role;

alter table public.courts enable row level security;
alter table public.bookings enable row level security;
alter table public.booking_players enable row level security;
alter table public.admins enable row level security;

grant all on public.courts, public.bookings, public.booking_players, public.admins to service_role;
grant usage, select on all sequences in schema public to service_role;
